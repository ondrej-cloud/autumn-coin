# Parsování dat
lines = [l.strip() for l in data.strip().split('\n')]
t, Ax, Ay, Bx, By = [], [], [], [], []

for line in lines:
    parts = line.replace(',', '.').split()
    if len(parts) == 3:
        # První řádek - přeskočíme
        continue
    elif len(parts) == 5:
        t.append(float(parts[0]))
        Ax.append(float(parts[1]))
        Ay.append(float(parts[2]))
        Bx.append(float(parts[3]))
        By.append(float(parts[4]))

t = np.array(t)
Ax, Ay = np.array(Ax), np.array(Ay)
Bx, By = np.array(Bx), np.array(By)

# ==========================================
# 2. NASTAVENÍ KONSTANTNÍHO POLOMĚRU
# ==========================================
r_const = 17.8 / 2.0  # = 8.9 mm

print(f"Použitý poloměr: {r_const} mm")

# ==========================================
# 3. VÝPOČET ÚHLOVÉ RYCHLOSTI
# ==========================================
dt = np.diff(t)

# Rychlost bodu B
vBx = np.diff(Bx) / dt
vBy = np.diff(By) / dt

# Vektor AB
ABx = Bx[1:] - Ax[1:]
ABy = By[1:] - Ay[1:]

# Tangenciální rychlost (kolmá složka)
v_tang = (vBx * ABy - vBy * ABx) / r_const

# Úhlová rychlost
omega = v_tang / r_const  # rad/s

# Vyhlazení
window = 5
omega_smooth = uniform_filter1d(omega, size=window, mode='nearest')

# ==========================================
# 4. VIZUALIZACE
# ==========================================
fig, ax = plt.subplots(figsize=(12, 6))

t_omega = t[1:]
ax.plot(t_omega, omega, 'b-', alpha=0.3, lw=1, label='ω (raw)')
ax.plot(t_omega, omega_smooth, 'r-', lw=2.5, label='ω (vyhlazená)')
ax.axhline(0, color='k', ls='--', alpha=0.3)
ax.set_xlabel('Čas [s]', fontsize=12)
ax.set_ylabel('Úhlová rychlost ω [rad/s]', fontsize=12)
ax.set_title(f'Úhlová rychlost (r = {r_const} mm = konstanta)', fontsize=14)
ax.legend(fontsize=11)
ax.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('angular_velocity.png', dpi=150)
plt.show()

# ==========================================
# 5. STATISTIKY
# ==========================================
print("\n" + "="*60)
print("STATISTIKA ÚHLOVÉ RYCHLOSTI")
print("="*60)
print(f"Průměr: {np.mean(omega_smooth):.3f} rad/s")
